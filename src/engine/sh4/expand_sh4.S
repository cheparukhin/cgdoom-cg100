/* void cgd_expand_p8_rgb565(uint16_t *dst, uint8_t const *src, uint16_t const *pal, int n) */
	CGD_SH4_EXPAND
	.balign 4
FUNC(cgd_expand_p8_rgb565)
	mov	#1, r0
	shll8	r0			/* 256 */
	cmp/ge	r0, r7
	bf	.Lxs_small
	/* build the rotated duplicated table on the stack, then run the fast core */
	sts.l	pr, @-r15
	mov	#-128, r0
	shll2	r0
	shll	r0			/* -1024 */
	add	r0, r15			/* r15 = table (1024 bytes, 4-aligned) */
	mov.l	r4, @-r15
	mov.l	r5, @-r15
	mov.l	r7, @-r15		/* stack: n, src, dst, [table 1 KiB], pr */
	mov	r15, r2
	add	#12, r2			/* r2 = table */
	mov	r2, r3
	mov	#127, r0
	add	#1, r0			/* 128 */
	mov	#64, r7			/* loop count: j, j+1 per iteration */
	add	r0, r0			/* 256 */
	mov	r6, r5
	add	r0, r5			/* r5 = &pal[128] */
	add	r0, r0			/* 512 */
	add	r0, r3			/* r3 = &table[128] */
	add	#-8, r3			/* (pre-decremented: the loop adds 8 first) */
	mov.l	r8, @-r15
	mov.l	r9, @-r15
	mov.l	r10, @-r15
	/* table[j] = dup(pal[j + 128]), table[j + 128] = dup(pal[j]), j < 128, two j per iteration:
	   8 LS + 11 EX + bf: 12 issue cycles, 13 per iteration with the taken branch (14 with GCC's
	   3-cycle loads), ~830 for the table.
	   dup(v): swap.w v,t; xtrct v,t = (v << 16) | v.
	   Hand-ordered in aligned LS|EX pairs (nop = padding that keeps the pairs aligned). */
	ALIGN4
cgd_xt_loop:
1:	mov.w	@r6+, r0		/* a = pal[j] */
	dt	r7
	mov.w	@r5+, r1		/* b = pal[j+128] */
	add	#8, r3
	mov.w	@r6+, r8		/* c = pal[j+1] */
	swap.w	r0, r4
	mov.w	@r5+, r9		/* d = pal[j+129] */
	xtrct	r0, r4			/* dup(a) */
	mov.l	r4, @r3			/* table[j+128] */
	swap.w	r1, r0
	xtrct	r1, r0			/* dup(b) */
	nop
	mov.l	r0, @r2			/* table[j] */
	swap.w	r8, r10
	xtrct	r8, r10			/* dup(c) */
	nop
	mov.l	r10, @(4,r3)		/* table[j+129] */
	swap.w	r9, r1
	xtrct	r9, r1			/* dup(d) */
	nop
	mov.l	r1, @(4,r2)		/* table[j+1] */
	add	#8, r2
	bf/s	1b
	nop
cgd_xt_end:
	mov.l	@r15+, r10
	mov.l	@r15+, r9
	mov.l	@r15+, r8
	mov.l	@r15+, r7
	mov.l	@r15+, r5
	mov.l	@r15+, r4
	mov.l	.Lxs_core, r0
	jsr	@r0
	mov	r15, r6			/* pal32 = table */
	mov.w	.Lxs_1024, r0
	add	r0, r15
	lds.l	@r15+, pr
	rts
	nop

.Lxs_small:	/* n < 256: dst[i] = pal[src[i]] directly (8-10 cycles/px; break-even ~175 px) */
	cmp/pl	r7
	bf	.Lxs_ret
cgd_xs_loop:
2:	mov.b	@r5+, r0
	extu.b	r0, r0
	add	r0, r0
	mov.w	@(r0,r6), r1
	dt	r7
	mov.w	r1, @r4
	bf/s	2b
	add	#2, r4
cgd_xs_end:
.Lxs_ret:
	rts
	nop

	.balign 2
.Lxs_1024:	.word	1024
	.balign 4
.Lxs_core:	.long	_cgd_expand_p8_rgb565_p32
ENDFUNC(cgd_expand_p8_rgb565)

