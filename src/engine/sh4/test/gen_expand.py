#!/usr/bin/env python3
"""gen_expand.py - generates ../expand_sh4.S (palette expansion + fill32).

    python3 gen_expand.py > ../expand_sh4.S

The inner loop of cgd_expand_p8_rgb565_p32 is a modulo-scheduled sequence: each pair of pixels
(2 source bytes -> one 32-bit store of two RGB565 values) is 10 instructions issued over a 5-cycle
period (5 LS + 3 EX + 2 MT: LS-bound, 2.5 cycles/pixel), 8 pairs per 32-byte destination line.
Per pair p (base time 5p, registers: x=r1, y=r2/r3 alternating, a=r8, b=r9, idx=r0):
    t-5 Lb0  mov.b @r5+,x        t-4 Lb1  mov.b @r5+,y        t-2 Sx shll2 x    t-1 Sy shll2 y
    t+0 Mx   mov x,r0            t+2 Lp0  mov.l @(r0,r6),a    t+2 My mov y,r0
    t+4 Lp1  mov.l @(r0,r6),b    t+6 X    xtrct a,b           t+8 ST mov.l b,@(4p,r4)
(r6 = pal32 + 512: the sign-extended byte times 4 indexes the rotated, duplicated palette;
xtrct a,b = (a << 16) | (b >>> 16) = (pal[s0] << 16) | pal[s1] since both entries are duplicated.)
Latencies honoured: load->EX 2, EX/MT->address 2, load->address >= 3 via the MT copy, EX->store 1+.
Two ops share a cycle with a write-after-read on r0 / x: the reader is emitted first.
The loop body is the 40-cycle window [8, 48) of a line: line l's ops in the window plus line l+1's
ops whose time is < 8 (prefetch of the next line). The last line runs a copy without those, so
the routine never reads src beyond src + npixels.
"""
import sys

OPS = [  # name, time offset, priority within cycle, template
    ("Lb0", -5, 1, "mov.b\t@r5+, r1"),
    ("Lb1", -4, 0, "mov.b\t@r5+, {y}"),
    ("Sx",  -2, 1, "shll2\tr1"),
    ("Sy",  -1, 1, "shll2\t{y}"),
    ("Mx",   0, 0, "mov\tr1, r0"),
    ("Lp0",  2, 0, "mov.l\t@(r0,r6), r8"),
    ("My",   2, 1, "mov\t{y}, r0"),
    ("Lp1",  4, 0, "mov.l\t@(r0,r6), r9"),
    ("X",    6, 1, "xtrct\tr8, r9"),
    ("ST",   8, 0, "mov.l\tr9, @({d},r4)"),
]
PERIOD, PAIRS, W0 = 5, 8, 8
WIN = PERIOD * PAIRS

def instances():
    """(time in window, prio, text, from_next_line) for one loop iteration."""
    out = []
    for line in (0, 1):
        for p in range(PAIRS):
            for (name, off, prio, tpl) in OPS:
                t = line * WIN + PERIOD * p + off
                if W0 <= t < W0 + WIN:
                    y = "r2" if p % 2 == 0 else "r3"
                    out.append((t, prio, tpl.format(y=y, d=4 * p) + "\t\t/* %s(%d)%s */" %
                                (name, p, " next line" if line else ""), line == 1))
    out.sort(key=lambda x: (x[0], x[1]))
    return out

def prologue():
    """Line 0's ops before the window (what the previous iteration would have done)."""
    out = []
    for p in range(PAIRS):
        for (name, off, prio, tpl) in OPS:
            t = PERIOD * p + off
            if t < W0:
                y = "r2" if p % 2 == 0 else "r3"
                out.append((t, prio, tpl.format(y=y, d=4 * p) + "\t\t/* %s(%d) */" % (name, p)))
    out.sort(key=lambda x: (x[0], x[1]))
    return [x[2] for x in out]

def body(last):
    return [x[2] for x in instances() if not (last and x[3])]

def emit_core(name, p1):
    L = []
    w = L.append
    lbl = ".Lx%s" % ("p1" if p1 else "oc")
    w("%s:\t/* %s destination */" % (lbl, "P1 cached SDRAM: movca.l + ocbp per line" if p1 else "on-chip / other: plain stores"))
    if p1:
        w("\tmovca.l\tr0, @r4\t\t\t/* allocate line 0 without fetching it */")
    for s in prologue():
        w("\t" + s)
    w("\ttst\tr7, r7")
    w("\tbt\t%s_last" % lbl)
    w("\tALIGN4")
    w("%s_loop:" % lbl)
    if not p1:
        w("cgd_x_loop:")
    else:
        w("cgd_x32_loop:")
    for s in body(False):
        w("\t" + s)
    if not p1:
        w("cgd_x_end:")
    else:
        w("cgd_x32_end:")
    if p1:
        w("\tocbp\t@r4\t\t\t/* write back + invalidate the finished line */")
        w("\tadd\t#32, r4")
        w("\tpref\t@r10")
        w("\tadd\t#16, r10")
        w("\tmovca.l\tr0, @r4\t\t\t/* allocate the next line */")
        w("\tdt\tr7")
    else:
        w("\tpref\t@r10")
        w("\tadd\t#32, r4")
        w("\tdt\tr7")
        w("\tadd\t#16, r10")
    w("\tbf\t%s_loop" % lbl)
    w("cgd_x32_next:" if p1 else "cgd_x_next:")
    w("\tALIGN4")
    w("%s_last:" % lbl)
    for s in body(True):
        w("\t" + s)
    if p1:
        w("\tocbp\t@r4")
    w("\tmov.l\t@r15+, r10")
    w("\tmov.l\t@r15+, r9")
    w("\trts")
    w("\tmov.l\t@r15+, r8")
    return L

HEADER = r'''/* expand_sh4.S - 8-bit -> RGB565 palette expansion for the presenter, and a cache-line fill.
   GENERATED by test/gen_expand.py (edit the generator, not this file).

   void cgd_expand_p8_rgb565_p32(uint16_t *dst, uint8_t const *src, uint32_t const *pal32, int n)
   void cgd_expand_p8_rgb565(uint16_t *dst, uint8_t const *src, uint16_t const *pal, int n)
   void cgd_fill32(void *dst, uint32_t value, size_t size)

   dst[i] = pal[src[i]], i < n.  Contract (src/gint/cgd_gint.h): n % 16 == 0, dst 32-byte aligned,
   dst either P1 cached SDRAM (0x80000000-0x9fffffff: each line is allocated with movca.l and
   purged with ocbp once written) or anything else, e.g. on-chip X/Y RAM (plain stores only).
   src: any alignment, read exactly once byte by byte, never beyond src + n.
   pal32 = cgd_expand_build_pal32(pal): pal32[k] = pal[k ^ 0x80] * 0x10001 (1 KiB, 4-aligned).
   cgd_expand_p8_rgb565 builds that table on its stack (1 KiB + 28 bytes peak; ~870 modelled
   cycles, ~940 under GCC's latencies) when n >= 256, else uses a simple loop (8-10 c/px). No DSP repeat loops, no DSP or MAC registers: these
   routines may run in interrupt context.

   Loop: 16 pixels (one destination line) per iteration, 80 + 5/7 instructions: 40 cycles LS-bound
   plus the line overhead, 45 modelled cycles = 2.81 cycles/pixel (3.3 with GCC's 3-cycle loads).
   See gen_expand.py for the schedule. */

#include "sh4_asm.h"

	CGD_SH4_EXPAND
	.balign 4
FUNC(cgd_expand_p8_rgb565_p32)
	mov	r7, r0
	tst	#15, r0			/* n must be a positive multiple of 16 */
	bf	.Lx_ret
	cmp/pl	r7
	bf	.Lx_ret
	mov.l	r8, @-r15
	mov	#2, r1
	mov.l	r9, @-r15
	shll8	r1			/* 512 */
	mov.l	r10, @-r15
	add	r1, r6			/* r6 = pal32 + 512 (index: sign-extended byte * 4) */
	shlr2	r7
	shlr2	r7			/* r7 = lines */
	add	#-1, r7			/* r7 = full loop iterations */
	/* prefetch pointer: 64 bytes (4 iterations) ahead when src is P1 RAM (pref beyond the end
	   cannot fault there), else the line being read (never outside the buffer) */
	mov	r5, r0
	shlr16	r0
	shlr8	r0
	shlr2	r0
	shlr	r0
	cmp/eq	#4, r0
	mov	r5, r10
	bf	1f
	add	#64, r10
1:	pref	@r5
	mov	r4, r0
	shlr16	r0
	shlr8	r0
	shlr2	r0
	shlr	r0			/* dst >> 29 */
	cmp/eq	#4, r0			/* P1 ? */
#ifdef CGD_SH4_TEST_FORCE_P1
	sett				/* test build: take the movca.l/ocbp path for any address */
#endif
	bt	.Lxp1
	bra	.Lxoc
	nop
.Lx_ret:
	rts
	nop
'''

def emit_plain():
    return r'''
/* void cgd_expand_p8_rgb565(uint16_t *dst, uint8_t const *src, uint16_t const *pal, int n) */
	CGD_SH4_EXPAND
	.balign 4
FUNC(cgd_expand_p8_rgb565)
	mov	#1, r0
	shll8	r0			/* 256 */
	cmp/ge	r0, r7
	bf	.Lxs_small
	/* build the rotated duplicated table on the stack, then run the fast core */
	sts.l	pr, @-r15
	mov	#-128, r0
	shll2	r0
	shll	r0			/* -1024 */
	add	r0, r15			/* r15 = table (1024 bytes, 4-aligned) */
	mov.l	r4, @-r15
	mov.l	r5, @-r15
	mov.l	r7, @-r15		/* stack: n, src, dst, [table 1 KiB], pr */
	mov	r15, r2
	add	#12, r2			/* r2 = table */
	mov	r2, r3
	mov	#127, r0
	add	#1, r0			/* 128 */
	mov	#64, r7			/* loop count: j, j+1 per iteration */
	add	r0, r0			/* 256 */
	mov	r6, r5
	add	r0, r5			/* r5 = &pal[128] */
	add	r0, r0			/* 512 */
	add	r0, r3			/* r3 = &table[128] */
	add	#-8, r3			/* (pre-decremented: the loop adds 8 first) */
	mov.l	r8, @-r15
	mov.l	r9, @-r15
	mov.l	r10, @-r15
	/* table[j] = dup(pal[j + 128]), table[j + 128] = dup(pal[j]), j < 128, two j per iteration:
	   8 LS + 11 EX + bf: 12 issue cycles, 13 per iteration with the taken branch (14 with GCC's
	   3-cycle loads), ~830 for the table.
	   dup(v): swap.w v,t; xtrct v,t = (v << 16) | v.
	   Hand-ordered in aligned LS|EX pairs (nop = padding that keeps the pairs aligned). */
	ALIGN4
cgd_xt_loop:
1:	mov.w	@r6+, r0		/* a = pal[j] */
	dt	r7
	mov.w	@r5+, r1		/* b = pal[j+128] */
	add	#8, r3
	mov.w	@r6+, r8		/* c = pal[j+1] */
	swap.w	r0, r4
	mov.w	@r5+, r9		/* d = pal[j+129] */
	xtrct	r0, r4			/* dup(a) */
	mov.l	r4, @r3			/* table[j+128] */
	swap.w	r1, r0
	xtrct	r1, r0			/* dup(b) */
	nop
	mov.l	r0, @r2			/* table[j] */
	swap.w	r8, r10
	xtrct	r8, r10			/* dup(c) */
	nop
	mov.l	r10, @(4,r3)		/* table[j+129] */
	swap.w	r9, r1
	xtrct	r9, r1			/* dup(d) */
	nop
	mov.l	r1, @(4,r2)		/* table[j+1] */
	add	#8, r2
	bf/s	1b
	nop
cgd_xt_end:
	mov.l	@r15+, r10
	mov.l	@r15+, r9
	mov.l	@r15+, r8
	mov.l	@r15+, r7
	mov.l	@r15+, r5
	mov.l	@r15+, r4
	mov.l	.Lxs_core, r0
	jsr	@r0
	mov	r15, r6			/* pal32 = table */
	mov.w	.Lxs_1024, r0
	add	r0, r15
	lds.l	@r15+, pr
	rts
	nop

.Lxs_small:	/* n < 256: dst[i] = pal[src[i]] directly (8-10 cycles/px; break-even ~175 px) */
	cmp/pl	r7
	bf	.Lxs_ret
cgd_xs_loop:
2:	mov.b	@r5+, r0
	extu.b	r0, r0
	add	r0, r0
	mov.w	@(r0,r6), r1
	dt	r7
	mov.w	r1, @r4
	bf/s	2b
	add	#2, r4
cgd_xs_end:
.Lxs_ret:
	rts
	nop

	.balign 2
.Lxs_1024:	.word	1024
	.balign 4
.Lxs_core:	.long	_cgd_expand_p8_rgb565_p32
ENDFUNC(cgd_expand_p8_rgb565)

/* void cgd_fill32(void *dst, uint32_t value, size_t size): dst 32-aligned, size % 32 == 0.
   P1 destinations: movca.l (no line fill); the lines stay in the cache. */
	CGD_SH4_EXPAND
	.balign 4
FUNC(cgd_fill32)
	shlr2	r6
	shlr2	r6
	shlr	r6			/* lines */
	tst	r6, r6
	bt	.Lf32_ret
	mov	r4, r0
	shlr16	r0
	shlr8	r0
	shlr2	r0
	shlr	r0
	cmp/eq	#4, r0
#ifdef CGD_SH4_TEST_FORCE_P1
	sett
#endif
	bf/s	.Lf32_plain
	mov	r5, r0
	ALIGN4
1:	movca.l	r0, @r4
	mov.l	r5, @(4,r4)
	mov.l	r5, @(8,r4)
	mov.l	r5, @(12,r4)
	mov.l	r5, @(16,r4)
	mov.l	r5, @(20,r4)
	mov.l	r5, @(24,r4)
	mov.l	r5, @(28,r4)
	dt	r6
	bf/s	1b
	add	#32, r4
	rts
	nop
	ALIGN4
.Lf32_plain:
2:	mov.l	r5, @r4
	mov.l	r5, @(4,r4)
	mov.l	r5, @(8,r4)
	mov.l	r5, @(12,r4)
	mov.l	r5, @(16,r4)
	mov.l	r5, @(20,r4)
	mov.l	r5, @(24,r4)
	mov.l	r5, @(28,r4)
	dt	r6
	bf/s	2b
	add	#32, r4
.Lf32_ret:
	rts
	nop
ENDFUNC(cgd_fill32)
'''

def main():
    out = [HEADER]
    out += emit_core("p1", True)
    out.append("")
    out += emit_core("oc", False)
    out.append("ENDFUNC(cgd_expand_p8_rgb565_p32)")
    out.append(emit_plain())
    print("\n".join(out))

if __name__ == "__main__":
    main()
