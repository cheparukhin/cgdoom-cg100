extern int	numtextures;	/* r_data.c */

static byte*	texturebm;	/* by texture number */
static byte*	flatbm;		/* by flat number */
static byte*	spritebm;	/* by sprite lump */

static byte* R_BrightmapTable (int count)
{
  byte *t = (byte *)Z_Malloc (count > 0 ? count : 1, PU_STATIC, NULL);

  memset (t, BM_NONE, count > 0 ? count : 1);
  return t;
}

void R_InitBrightmaps (void)
{
  const int	game = gamemode == commercial ? DOOM2ONLY : DOOM1ONLY;
  unsigned	i, j;

  texturebm = R_BrightmapTable (numtextures);
  for (i = 0; i < sizeof fullbright_doom / sizeof *fullbright_doom; i++)
  {
    const fullbright_t *fb = &fullbright_doom[i];
    int tex;

    if (fb->game != DOOM1AND2 && fb->game != game)
      continue;
    tex = R_CheckTextureNumForName (fb->texture);
    if (tex > 0)		/* 0 is "no texture" */
      texturebm[tex] = fb->brightmap;
  }

  flatbm = R_BrightmapTable (numflats);
  for (i = 0; i < sizeof fullbright_flats / sizeof *fullbright_flats; i++)
  {
    int flat = W_CheckNumForName (fullbright_flats[i]) - firstflat;

    if (flat >= 0 && flat < numflats)
      flatbm[flat] = FLAT_BRIGHTMAP;
  }

  /* A sprite lump belongs to the sprite whose name is the first four
     characters of its own (R_InitSpriteDefs) */
  spritebm = R_BrightmapTable (numspritelumps);
  for (i = 0; i < (unsigned)numspritelumps; i++)
  {
    const char *name = lumpinfo[firstspritelump + i].name;

    for (j = 0; j < sizeof fullbright_sprites / sizeof *fullbright_sprites; j++)
      if (!memcmp (name, sprnames[fullbright_sprites[j].sprite], 4))
        spritebm[i] = fullbright_sprites[j].brightmap;
  }
}

const byte* R_TextureBrightmap (int texnum)
{
  return brightmaps[texturebm[texnum]];
}

const byte* R_FlatBrightmap (int flatnum)
{
  return brightmaps[flatbm[flatnum]];
}

const byte* R_SpriteBrightmap (int spritelump)
{
  return brightmaps[spritebm[spritelump]];
}

/* The BFG9000's firing frames */
const byte* R_StateBrightmap (int state)
{
  switch (state)
  {
    case S_BFG1:
    case S_BFG2:
    case S_BFG3:
    case S_BFG4:
      return redonly;
  }
  return NULL;
}

